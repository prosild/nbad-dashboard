-- T56 대응 조치 기록(PostgreSQL V5와 같은 구조). H2는 시험 전용이다.
-- H2에는 초기화 함수가 없고 트리거(H2ResponseActionImmutableTrigger)는 UPDATE·DELETE를 늘 거부한다.
-- 표식이 있을 때만 통과하는 DELETE와 TRUNCATE 차단은 PostgreSQL에서만 있고 scripts/audit-retention-check.ps1이 PostgreSQL에서 직접 시험한다.
-- note 길이: H2는 VARCHAR 길이를 UTF-16 단위로 세므로 보조 평면 문자 500개(코드 포인트 500)를 담게 1000으로 둔다. 상한(500 코드 포인트)은 앱이 막는다.

CREATE TABLE incident_response_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id VARCHAR(255) NOT NULL,
    capture_id VARCHAR(128) NOT NULL,
    job_id BIGINT NOT NULL,
    action_type VARCHAR(32) NOT NULL CHECK (action_type IN (
        'block_ip', 'isolate_host', 'lock_account', 'handover', 'monitor', 'none', 'other')),
    note VARCHAR(1000),
    actor_username VARCHAR(100) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_incident_response_actions_incident ON incident_response_actions (incident_id);

CREATE TRIGGER trg_incident_response_actions_immutable
BEFORE UPDATE, DELETE ON incident_response_actions
FOR EACH ROW
CALL "com.zeekad.dashboard.audit.H2ResponseActionImmutableTrigger";
