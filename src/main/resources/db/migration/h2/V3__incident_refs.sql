-- T27 인시던트 번호(PostgreSQL V3와 같은 구조). H2는 시험 전용이다.

CREATE TABLE incident_refs (
    incident_no BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id VARCHAR(255) NOT NULL UNIQUE,
    capture_id VARCHAR(128) NOT NULL,
    detected_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TRIGGER trg_incident_refs_immutable
BEFORE UPDATE, DELETE ON incident_refs
FOR EACH ROW
CALL "com.zeekad.dashboard.audit.H2IncidentRefsImmutableTrigger";
