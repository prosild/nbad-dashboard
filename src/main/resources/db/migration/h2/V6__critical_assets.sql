-- T52 중요 자산(PostgreSQL V6과 같은 구조). H2는 시험 전용이다.
-- 이름·설명 길이: H2는 VARCHAR 길이를 UTF-16 단위로 세므로 보조 평면 문자 100·300개(코드 포인트)를 담게 두 배로 둔다.
-- 상한(100·300 코드 포인트)은 앱이 막는다.

CREATE TABLE critical_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_ip VARCHAR(15) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(600),
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
